// Hostinger build of apps/web, run by scripts/build.mjs when HOSTINGER_BUILD=1.
//
// 1. `next build` for apps/web with HOSTINGER_BUILD=1, so next.config.ts sets output: 'standalone'.
//    Next is located with Node's module resolution from apps/web and run with the current Node:
//    no nested pnpm/Corepack, and no assumption about the node_modules layout the install
//    produced (pnpm isolated or hoisted).
// 2. Turns apps/web/.next/standalone into the publish root Hostinger serves (output directory
//    apps/web/.next/standalone, entry file server.js):
//      server.js                         only requires apps/web/server.js, the server Next generated
//      apps/web/.next/static, apps/web/public   copied next to that server, as Next documents
//    node_modules stays exactly as traced by Next; .env files are never copied.
import { spawnSync } from 'node:child_process'
import { cpSync, existsSync, lstatSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const webDir = path.join(rootDir, 'apps', 'web')
const requireFromWeb = createRequire(path.join(webDir, 'package.json'))

function fail(message) {
  console.error(`[hostinger-web-build] ${message}`)
  process.exit(1)
}

// Only reports which node_modules directories inside the repo hold `next` (no env vars).
function describeLookupDir(dir) {
  if (!existsSync(dir)) return 'missing'
  const next = path.join(dir, 'next')
  if (existsSync(next)) return 'has next'
  try {
    lstatSync(next)
    return 'next is a broken link'
  } catch {
    return 'no next'
  }
}

let nextPackageJson
try {
  nextPackageJson = requireFromWeb.resolve('next/package.json')
} catch (error) {
  const lookup = (requireFromWeb.resolve.paths('next') ?? [])
    .filter((dir) => !path.relative(rootDir, dir).startsWith('..'))
    .map((dir) => `${path.relative(rootDir, dir)}: ${describeLookupDir(dir)}`)
  fail(`cannot resolve next from apps/web (${error.code ?? error.message}); ${lookup.join(', ')}`)
}

const nextPackage = JSON.parse(readFileSync(nextPackageJson, 'utf8'))
const binEntry = typeof nextPackage.bin === 'string' ? nextPackage.bin : nextPackage.bin?.next
if (!binEntry) fail(`next ${nextPackage.version} declares no "next" bin`)
const nextBin = path.join(path.dirname(nextPackageJson), binEntry)
console.log(`[hostinger-web-build] next ${nextPackage.version}: ${path.relative(rootDir, nextBin)}`)

const result = spawnSync(process.execPath, [nextBin, 'build'], {
  cwd: webDir,
  stdio: 'inherit',
  env: { ...process.env, HOSTINGER_BUILD: '1' },
})
if (result.error) fail(`could not start next build: ${result.error.message}`)
if (result.signal) process.kill(process.pid, result.signal)
if (result.status !== 0) process.exit(result.status ?? 1)

const standaloneDir = path.join(webDir, '.next', 'standalone')
const appRel = path.relative(rootDir, webDir).split(path.sep).join('/')
const standaloneApp = path.join(standaloneDir, appRel)
if (!existsSync(path.join(standaloneApp, 'server.js'))) {
  fail(`next build did not generate apps/web/.next/standalone/${appRel}/server.js`)
}
const notEnvFile = (src) => !path.basename(src).startsWith('.env')
for (const [from, to] of [
  [path.join(webDir, '.next', 'static'), path.join(standaloneApp, '.next', 'static')],
  [path.join(webDir, 'public'), path.join(standaloneApp, 'public')],
]) {
  rmSync(to, { recursive: true, force: true })
  cpSync(from, to, { recursive: true, filter: notEnvFile })
}
writeFileSync(
  path.join(standaloneDir, 'server.js'),
  '// Hostinger entry point, generated by scripts/hostinger-web-build.mjs.\n' +
    `// Loads the standalone server that Next generated for ${appRel}.\n` +
    `require('./${appRel}/server.js')\n`
)
console.log(
  `[hostinger-web-build] publish root apps/web/.next/standalone: server.js -> ${appRel}/server.js, static and public copied`
)
